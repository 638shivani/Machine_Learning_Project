import pandas as pd
import gradio as gr

# ============================================================
# 2. LOAD DATASET
# ============================================================
df = pd.read_excel("/content/drive/MyDrive/Demo/ last_genetic_disorders_modified_no_disorder.csv")

# ============================================================
# 3. SELECT 21 FEATURES
# ============================================================
features = [
    "Patient Age",
    "Genes in mother's side",
    "Inherited from father",
    "Maternal gene",
    "Paternal gene",
    "Blood cell count (mcL)",
    "White Blood cell count (thousand per microliter)",
    "Blood test result",
    "Mother's age",
    "Father's age",
    "Status",
    "Respiratory Rate (breaths/min)",
    "Birth defects",
    "History of anomalies in previous pregnancies",
    "No. of previous abortion",
    "Symptom 1",
    "Symptom 2",
    "Symptom 3",
    "Symptom 4",
    "Symptom 5",
    "H/O serious maternal illness"
]

target = "Disorder Subclass"

df_small = df[features + [target]].astype(str)

# ============================================================
# 4. NORMALIZATION FUNCTION
# ============================================================
def normalize(v):
    v = str(v).strip().lower()

    if v in ["", "nan", "none", "-", "missing", "not applicable", "not available", "no record"]:
        return "missing"

    if v in ["yes", "y"]:
        return "yes"
    if v in ["no", "n"]:
        return "no"

    # Convert numeric safely
    try:
        return str(float(v))
    except:
        return v

# apply normalizer to entire dataset
df_norm = df_small.copy()
for col in features:
    df_norm[col] = df_norm[col].apply(normalize)

# ============================================================
# 5. PREDICT FUNCTION (ROW MATCHING)
# ============================================================
def predict_diabetes(*inputs):

    user = {features[i]: normalize(inputs[i]) for i in range(len(features))}

    mask = pd.Series([True] * len(df_norm))
    for col in features:
        mask &= (df_norm[col] == user[col])

    match = df_norm[mask]

    if match.empty:
        return "⚠ No exact matching record found in dataset"

    result = match[target].iloc[0].lower()

    return "🟥 Diabetes" if result == "diabetes" else "🟩 Non-Diabetes"

# ============================================================
# 6. GRADIO INTERFACE
# ============================================================
inputs_ui = [gr.Textbox(label=f) for f in features]

app = gr.Interface(
    fn=predict_diabetes,
    inputs=inputs_ui,
    outputs="text",
    title="Genetic Diabetes Checker (21 Features)",
    description="Matches 21 full features from dataset to determine diabetes status."
)

app.launch(share=True)

